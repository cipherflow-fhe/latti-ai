// Benchmark: CKKS primitive op GPU latency for all ops in score.py:
//   add        (ct+ct)   : level 0 ~ max_level
//   rotate     (ct,step) : level 0 ~ max_level
//   mult_plain (ct*pt)   : level 1 ~ max_level
//   mult       (ct*ct + relin) : level 1 ~ max_level
//   rescale    (ct)      : level 1 ~ max_level
//
// N values: 8192, 16384, 32768, 65536
// One FheTaskGpu instruction directory per (op, N, level).
// Run benchmark_ckks_ops_gpu.py first to generate them.
//
// Usage:
//   benchmark_ckks_ops_gpu [op] [N] [output.txt]
//   op  : add | mult_plain | mult | rotate | rescale | all  (default: all)
//   N   : 8192 | 16384 | 32768 | 65536                      (default: all)

#include <cxx_sdk_v2/cxx_fhe_task.h>
#include <fhe_ops_lib/fhe_lib_v2.h>

#include <cstdarg>
#include <cstdio>
#include <cstring>
#include <string>
#include <vector>

using namespace cxx_sdk_v2;
using namespace fhe_ops_lib;
using namespace std;

static const int N_OPS_DEFAULT = 16;
static const int N_OPS_LARGE = 16;  // N=65536: larger polynomials, fewer per batch

// batch size must match the instruction files generated by the Python script
static int n_ops_for_N(int N) {
    return (N == 65536) ? N_OPS_LARGE : N_OPS_DEFAULT;
}

static const int N_WARM = 3;

// max benchmark level per N (from parameter.json max_level field)
static int max_bench_level(int N) {
    if (N == 8192)
        return 5;
    if (N == 16384)
        return 9;
    if (N == 32768)
        return 17;
    return 33;  // 65536
}

// ---------------------------------------------------------------------------
// Output: mirror to stdout + optional file
// ---------------------------------------------------------------------------

static FILE* g_out = nullptr;

static void outf(const char* fmt, ...) {
    va_list ap;
    va_start(ap, fmt);
    vprintf(fmt, ap);
    va_end(ap);
    if (g_out) {
        va_start(ap, fmt);
        vfprintf(g_out, fmt, ap);
        va_end(ap);
    }
}

// ---------------------------------------------------------------------------
// Instruction directory path
// SOURCE_PATH is set by inference/CMakeLists.txt to the inference/ source dir.
// ---------------------------------------------------------------------------

static string task_path(const char* op, int N, int level) {
    return string(SOURCE_PATH) + "/benchmark_ckks_ops_gpu/" + op + "_n" + to_string(N) + "_l" + to_string(level);
}

// ---------------------------------------------------------------------------
// Per-op benchmark functions
// CkksCiphertext/CkksPlaintext are move-only; always construct fresh via
// push_back with rvalue expressions, never copy.
//
// Warmup and timed run both use the same N_OPS-sized batch (the task expects
// exactly N_OPS elements — matching the instruction file generated by the
// Python script).  We build the batch once, run N_WARM times (discarding
// timing), then run once more and record the time.
// ---------------------------------------------------------------------------

static void bench_add(CkksContext& ctx, const CkksParameter& param, int N) {
    outf("\n[add]  N=%d\n", N);
    outf("%-8s  %-14s  %-14s\n", "level", "time_ms", "per_op_ms");
    outf("%s\n", string(40, '-').c_str());

    double scale = param.get_default_scale();
    int max_lv = max_bench_level(N);
    int n_ops = n_ops_for_N(N);
    vector<double> vals(N / 2, 1.0);

    for (int lv = 0; lv <= max_lv; lv++) {
        try {
            auto pt = ctx.encode(vals, lv, scale);
            FheTaskGpu task(task_path("ckks_add", N, lv));

            vector<CkksCiphertext> xs, ys, zs;
            for (int i = 0; i < n_ops; i++) {
                xs.push_back(ctx.encrypt_asymmetric(pt));
                ys.push_back(ctx.encrypt_asymmetric(pt));
                zs.push_back(ctx.new_ciphertext(lv, scale));
            }

            vector<CxxVectorArgument> args = {{"xs", &xs}, {"ys", &ys}, {"zs", &zs}};
            for (int w = 0; w < N_WARM; w++)
                task.run(&ctx, args, false);
            uint64_t t_ns = task.run(&ctx, args, false);
            double total_ms = t_ns / 1.0e6;
            outf("%-8d  %-14.3f  %-14.4f\n", lv, total_ms, total_ms / n_ops);
        } catch (const exception& e) { outf("%-8d  error: %s\n", lv, e.what()); }
    }
}

