// ---------------------------------------------------------------------------
// main
// ---------------------------------------------------------------------------

using BenchFn = void (*)(CkksContext&, const CkksParameter&, int);
struct OpEntry {
    const char* name;
    BenchFn fn;
};

static const OpEntry ALL_OPS[] = {
    {"add", bench_add},   {"rotate", bench_rotate},   {"mult_plain", bench_mult_plain},
    {"mult", bench_mult}, {"rescale", bench_rescale},
};
static const int N_ALL_OPS = sizeof(ALL_OPS) / sizeof(ALL_OPS[0]);
static const int ALL_NS[] = {8192, 16384, 32768, 65536};
static const int N_ALL_NS = sizeof(ALL_NS) / sizeof(ALL_NS[0]);

int main(int argc, char* argv[]) {
    const char* help = "Usage: benchmark_ckks_ops_gpu [op] [N] [output.txt]\n"
                       "  op         : add | mult_plain | mult | rotate | rescale | all (default: all)\n"
                       "  N          : 8192 | 16384 | 32768 | 65536                     (default: all)\n"
                       "  output.txt : optional file to write results\n"
                       "\nRun benchmark_ckks_ops_gpu.py first to generate instruction files.\n";

    const char* op_arg = "all";
    int N_arg = 0;
    const char* out_arg = nullptr;

    if (argc >= 2) {
        op_arg = argv[1];
        if (strcmp(op_arg, "-h") == 0 || strcmp(op_arg, "--help") == 0) {
            printf("%s", help);
            return 0;
        }
    }
    if (argc >= 3)
        N_arg = stoi(argv[2]);
    if (argc >= 4)
        out_arg = argv[3];

    if (out_arg) {
        g_out = fopen(out_arg, "w");
        if (!g_out) {
            fprintf(stderr, "Cannot open: %s\n", out_arg);
            return 1;
        }
    }

    outf("=== CKKS primitive op GPU benchmark ===\n\n");

    for (int ni = 0; ni < N_ALL_NS; ni++) {
        int N = ALL_NS[ni];
        if (N_arg != 0 && N != N_arg)
            continue;

        outf("==============================\n");
        outf("N = %d  (n_slot=%d, max_bench_level=%d, n_ops=%d)\n", N, N / 2, max_bench_level(N), n_ops_for_N(N));
        outf("==============================\n");

        try {
            auto param = CkksParameter::create_parameter(N);
            auto ctx = CkksContext::create_random_context(param);

            for (int oi = 0; oi < N_ALL_OPS; oi++) {
                const OpEntry& e = ALL_OPS[oi];
                if (strcmp(op_arg, "all") != 0 && strcmp(op_arg, e.name) != 0)
                    continue;
                e.fn(ctx, param, N);
            }
        } catch (const exception& e) { fprintf(stderr, "Failed to init N=%d: %s\n", N, e.what()); }
        outf("\n");
    }

    if (g_out) {
        fclose(g_out);
        printf("\nResults written to: %s\n", out_arg);
    }
    return 0;
}
