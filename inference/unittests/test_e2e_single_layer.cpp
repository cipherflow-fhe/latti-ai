// Single-layer E2E inference tests.
//
// Test data is generated by running test_compiler.py::TestE2ESingleLayer which
// produces complete task directories under build/inference/hetero_e2e/single_layer/.
//
// The test list is loaded from ut_names.json (written by the Python test
// after each successful _export_compile_and_deploy call). This avoids stale
// directories left over from deleted Python tests being picked up.
//
// Usage:
//   ./test_e2e_single_layer "[e2e]"                    # Run all tests
//   ./test_e2e_single_layer "[cpu]"                    # Run all CPU tests
//   ./test_e2e_single_layer "[gpu]"                    # Run all GPU tests
//   ./test_e2e_single_layer "cpu/all" -c "conv"        # Run a specific CPU test
//   ./test_e2e_single_layer "cpu/all" -c "conv2d_*"    # Run tests matching pattern

