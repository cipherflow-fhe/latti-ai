// Read test names from ut_names.json written by the Python test suite.
// Falls back to empty list if the manifest does not exist.
static std::vector<std::string> load_test_names(const fs::path& base) {
    std::vector<std::string> names;
    fs::path manifest = base / "ut_names.json";
    if (!fs::exists(manifest))
        return names;
    auto j = read_json(manifest.string());
    for (const auto& entry : j) {
        names.push_back(entry.get<std::string>());
    }
    return names;
}

