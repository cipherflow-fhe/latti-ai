#!/usr/bin/env python3
"""Build the distributable Retina browser package.

The WASM archive is copied byte-for-byte from the supplied 0.1.1 package.  The
two Retina archives are assembled from the already validated demo resources;
the classifier CSV files are intentionally generated by ``preprocess.js`` at
run time rather than shipped as a second copy of the dataset.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import tempfile
import zipfile
from pathlib import Path


WASM_NAME = 'latti-client-wasm-0.1.1.zip'
TASK_NAME = 'latti-retina-tasks-0.1.1.zip'
DATASET_NAME = 'latti-retina-dataset-degree8-02-0.1.1.zip'
PACKAGE_NAME = 'latti-retina-degree8-02-0.1.1.zip'


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open('rb') as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b''):
            digest.update(chunk)
    return digest.hexdigest()


def write_zip(source_root: Path, output: Path, paths: list[tuple[Path, str]]) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(output, 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for source, name in paths:
            if source.is_dir():
                for child in sorted(source.rglob('*')):
                    if child.is_file():
                        archive.write(child, name + '/' + child.relative_to(source).as_posix())
            else:
                archive.write(source, name)


def make_readme(path: Path) -> None:
    path.write_text(
        """# Retina-DKD degree8_02 browser package

This package combines the reusable `latti-client-wasm-0.1.1` browser client,
the Retina task scripts, and the ten-image Retina dataset. The WASM archive is
copied unchanged from `/tmp/latti-client-wasm-0.1.1.zip`; it does not need to
be rebuilt for this task.

## Contents

| Archive | Contents |
| --- | --- |
| `packages/latti-client-wasm-0.1.1.zip` | Browser key generation, restore, CSV encryption and decryption |
| `packages/latti-retina-tasks-0.1.1.zip` | `preprocess.js`, `postprocess.js`, `task_config.json`, `ckks_parameter.json` |
| `packages/latti-retina-dataset-degree8-02-0.1.1.zip` | Ten original test images, disk/lesion masks, `risk_factor_5.xlsx`, and `label.csv` |

Unpack the three archives into a static web application's vendor/task/data
directories. Select `dataset/` as the input directory for `preprocess_batch`;
it creates `input_0`, `input_1`, and `input_2` CSVs. Pass each CSV directory to
the reusable WASM client's `encrypt_batch` with the matching input name.

The server input package is flat and uses one entry per feature:
`<case_id>__input_0.ct`, `<case_id>__input_1.ct`, and
`<case_id>__input_2.ct`. Submit it to the local server as model
`retina-multimodal-seg` (or the configured `retina-multimodal` model) and place
the returned `<case_id>.result.bin` in a directory for
`decrypt_batch({outputName: 'output', ...})`. Finally call `postprocess_batch`
with `dataset/label.csv` to compute the argmax prediction and accuracy.

The package's ten labels and masks are also available in the full validation
demo at `/LattiAI-Task-Resources/retina_degree8_02/task/client/demo_10/`.
The historical reference logits in that demo produce 9/10 (90%); a new server
run must report accuracy from its own decrypted logits.

## Server-side model

The browser package does not include the 444 MiB native model server files.
The local `latti-client` deployment already registers the matching server task
as `retina-multimodal-seg`; its server directory must contain the same
`task_config.json`, `ckks_parameter.json`, `mega_ag.json`,
`nn_layers_ct_0.json`, `model_parameters.h5`, and `task_signature.json` as the
Retina task resource. The server receives only `eval_context.bin` and the
ciphertexts; the full secret context remains in the browser.

All package members are listed in `manifest.json` and verified by
`SHA256SUMS`.
""",
        encoding='utf-8',
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        '--wasm-zip',
        type=Path,
        default=Path('/tmp/latti-client-wasm-0.1.1.zip'),
    )
    parser.add_argument(
        '--demo-dir',
        type=Path,
        default=Path('/LattiAI-Task-Resources/retina_degree8_02/task/client/demo_10'),
    )
    parser.add_argument(
        '--output-dir',
        type=Path,
        default=Path('/LattiAI-Task-Resources/retina_degree8_02'),
    )
    args = parser.parse_args()
    wasm_zip = args.wasm_zip.resolve()
    demo_dir = args.demo_dir.resolve()
    output_dir = args.output_dir.resolve()
    client_dir = demo_dir / 'client'
    dataset_dir = demo_dir / 'dataset'
    required_client = ['preprocess.js', 'postprocess.js', 'task_config.json', 'ckks_parameter.json']
    if not wasm_zip.is_file():
        raise SystemExit(f'WASM archive not found: {wasm_zip}')
    for name in required_client:
        if not (client_dir / name).is_file():
            raise SystemExit(f'missing task client file: {client_dir / name}')
    for name in ['images', 'disk', 'lesion', 'risk_factor_5.xlsx', 'label.csv']:
        if not (dataset_dir / name).exists():
            raise SystemExit(f'missing dataset resource: {dataset_dir / name}')

    with tempfile.TemporaryDirectory(prefix='latti-retina-package.') as temp_name:
        stage = Path(temp_name) / 'latti-retina-degree8-02-0.1.1'
        packages = stage / 'packages'
        packages.mkdir(parents=True)
        wasm_destination = packages / WASM_NAME
        # copy2 preserves the supplied archive's bytes and metadata; hash is
        # checked again below so an accidental rebuild cannot pass silently.
        shutil.copy2(wasm_zip, wasm_destination)

        task_zip = packages / TASK_NAME
        task_paths = [(client_dir / name, f'tasks/retina_degree8_02/client/{name}') for name in required_client]
        write_zip(stage, task_zip, task_paths)

        dataset_zip = packages / DATASET_NAME
        dataset_paths: list[tuple[Path, str]] = []
        for name in ['images', 'disk', 'lesion']:
            dataset_paths.append((dataset_dir / name, f'dataset/{name}'))
        for name in ['risk_factor_5.xlsx', 'label.csv']:
            dataset_paths.append((dataset_dir / name, f'dataset/{name}'))
        write_zip(stage, dataset_zip, dataset_paths)

        make_readme(stage / 'README.md')
        manifest = {
            'package': 'latti-retina-degree8-02',
            'version': '0.1.1',
            'wasm': {'archive': f'packages/{WASM_NAME}', 'source': str(wasm_zip)},
            'task': {
                'archive': f'packages/{TASK_NAME}',
                'model_id': 'retina-multimodal-seg',
                'required_inputs': ['input_0', 'input_1', 'input_2'],
                'output_name': 'output',
            },
            'dataset': {
                'archive': f'packages/{DATASET_NAME}',
                'samples': 10,
                'accuracy_basis': 'historical reference logits in the full demo, 9/10',
            },
            'server_contract': {
                'input_entry': '<case_id>__<input_name>.ct',
                'result_entry': '<case_id>.result.bin',
                'eval_context': '<keys_dir>/<user_id>/eval_context.bin',
            },
        }
        (stage / 'manifest.json').write_text(
            json.dumps(manifest, indent=2, ensure_ascii=False) + '\n', encoding='utf-8'
        )

        checksum_paths = [stage / 'README.md', stage / 'manifest.json', wasm_destination, task_zip, dataset_zip]
        (stage / 'SHA256SUMS').write_text(
            ''.join(f'{sha256(path)}  {path.relative_to(stage).as_posix()}\n' for path in checksum_paths),
            encoding='utf-8',
        )

        output_dir.mkdir(parents=True, exist_ok=True)
        output_zip = output_dir / PACKAGE_NAME
        if output_zip.exists():
            output_zip.unlink()
        with zipfile.ZipFile(output_zip, 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
            for path in sorted(stage.rglob('*')):
                if path.is_file():
                    archive.write(path, path.relative_to(stage.parent).as_posix())
        digest = sha256(output_zip)
        (output_zip.with_suffix(output_zip.suffix + '.sha256')).write_text(
            f'{digest}  {output_zip.name}\n', encoding='utf-8'
        )
        print(json.dumps({'package': str(output_zip), 'bytes': output_zip.stat().st_size, 'sha256': digest}, indent=2))


if __name__ == '__main__':
    main()
